
import nodemailer from "nodemailer";

import {
  SMTP_HOST,
  SMTP_PORT,
  SMTP_USERNAME,
  SMTP_PASSWORD,
  SMTP_FROM,
  SMTP_FROM_NAME,
  MAIL_TO,
} from "./mailConfig.js";

// Validate SMTP configuration
if (!SMTP_USERNAME || !SMTP_PASSWORD) {
  throw new Error(
    "SMTP_USERNAME or SMTP_PASSWORD is missing in .env"
  );
}

if (!MAIL_TO) {
  throw new Error("MAIL_TO is missing in .env");
}

// Create transporter
const transporter = nodemailer.createTransport({
  host: SMTP_HOST,
  port: Number(SMTP_PORT),
  secure: Number(SMTP_PORT) === 465,

  auth: {
    user: SMTP_USERNAME,
    pass: SMTP_PASSWORD,
  },
});

// Verify SMTP connection
transporter.verify((error) => {
  if (error) {
    console.error("❌ SMTP connection failed:", error.message);
  } else {
    console.log("✅ SMTP server is ready to send emails");
  }
});

// Escape HTML to protect email content
function escapeHTML(value) {
  return String(value ?? "N/A")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

// Builds an HTML table from form fields
function buildFieldsHTML(fields) {
  return Object.entries(fields)
    .filter(([key]) => key !== "formType")
    .map(
      ([key, value]) => `
        <tr>
          <td style="
            padding:8px;
            border:1px solid #ddd;
            font-weight:bold;
            text-transform:capitalize;
          ">
            ${escapeHTML(key.replace(/([A-Z])/g, " $1"))}
          </td>

          <td style="padding:8px;border:1px solid #ddd;">
            ${escapeHTML(value)}
          </td>
        </tr>
      `
    )
    .join("");
}

// Send form submission email
export async function sendFormMail(formType, fields) {
  console.log(`📩 Sending mail for: ${formType}`);

  const mailOptions = {
    from: `"${SMTP_FROM_NAME}" <${SMTP_FROM}>`,

    replyTo: fields.email || SMTP_FROM,

    to: MAIL_TO,

    subject: `New Submission — ${formType}`,

    html: `
      <div style="font-family:Arial,sans-serif;">
        <h2>New ${escapeHTML(formType)} Submission</h2>

        <table style="
          border-collapse:collapse;
          width:100%;
          max-width:600px;
        ">
          ${buildFieldsHTML(fields)}
        </table>

        <p style="margin-top:20px;color:#777;">
          This email was automatically generated by Divine Interior.
        </p>
      </div>
    `,
  };

  try {
    const info = await transporter.sendMail(mailOptions);

    console.log(
      "✅ Mail sent successfully. Message ID:",
      info.messageId
    );

    return info;
  } catch (error) {
    console.error("❌ Failed to send email:", error.message);
    throw error;
  }
}

export default transporter;
